import { dirname, relative, resolve, sep } from 'node:path';
import type { FunctionAnalysis } from './function-analysis.ts';
import { runtimeExportConditions } from './runtime-conditions.ts';
import { isImportDeclaration, isExportDeclaration, isStringLiteral } from './development-compiler.ts';

const header = '// Generated by @hulla/db. Do not edit.\n';

/** Bundle only the inert schema/codecs. Application startup and handlers stay outside the graph. */
export async function generateSource(source: string, exported: string, outDir: string, analysis: FunctionAnalysis, engine: string): Promise<{ wrapper: string; bundle: string; declaration: string }> {
  const declaration = (await analysis.databaseDeclarations(source)).find(value => value.exportName === exported);
  const schema = declaration?.schemaExport;
  if (!schema) throw new TypeError('Generation requires a schema exported from a separate inert authoring module');
  const core = new Map(['index', 'schema', 'zod'].map(name => [Bun.fileURLToPath(new URL(`./${name}.ts`, import.meta.url)), name === 'index' ? '@hulla/db' : `@hulla/db/${name}`]));
  const build = await Bun.build({
    entrypoints: ['__hulla_shared_source__'], target: 'browser', format: 'esm', packages: 'external', conditions: runtimeExportConditions(), throw: false,
    plugins: [{ name: 'hulla-shared-source', setup(builder) {
      builder.onResolve({ filter: /^__hulla_shared_source__$/ }, () => ({ path: resolve(outDir, '_source-entry.ts'), namespace: 'hulla-source' }));
      builder.onLoad({ filter: /.*/, namespace: 'hulla-source' }, () => ({ contents: `import { ${JSON.stringify(schema.name)} as schema } from ${JSON.stringify(schema.file)}\nimport { schemaIdentity } from '@hulla/db/internal/engine'\nexport default schemaIdentity(schema)\nexport const engine = ${JSON.stringify(engine)}`, loader: 'ts', resolveDir: dirname(source) }));
      builder.onLoad({ filter: /\.[cm]?[tj]sx?$/, namespace: 'file' }, async args => {
        if (args.path.includes(`${sep}node_modules${sep}`)) return undefined;
        const project = await analysis.project(args.path);
        const file = await project.program.getSourceFile(args.path);
        const patches = [];
        for (const statement of file?.statements ?? []) {
          if ((!isImportDeclaration(statement) && !isExportDeclaration(statement)) || !statement.moduleSpecifier || !isStringLiteral(statement.moduleSpecifier) || !statement.moduleSpecifier.text.startsWith('.')) continue;
          const external = core.get(Bun.resolveSync(statement.moduleSpecifier.text, dirname(args.path)));
          if (external) patches.push({ start: statement.moduleSpecifier.pos, end: statement.moduleSpecifier.end, text: JSON.stringify(external) });
        }
        if (!patches.length) return undefined;
        let contents = await Bun.file(args.path).text();
        for (const patch of patches.sort((a, b) => b.start - a.start)) contents = contents.slice(0, patch.start) + patch.text + contents.slice(patch.end);
        return { contents, loader: /\.[cm]?jsx?$/.test(args.path) ? 'jsx' : 'tsx', resolveDir: dirname(args.path) };
      });
    } }],
  });
  if (!build.success || build.outputs.length !== 1) throw new TypeError(`Cannot generate shared schema source:\n${build.logs.map(log => log.message).join('\n')}`);
  const path = relative(outDir, source).split(sep).join('/');
  const specifier = path.startsWith('.') ? path : `./${path}`;
  const wrapper = `${header}\nexport { default as source } from './_source.js'\n`;
  const types = `${header}\nimport type { DatabaseSource } from '@hulla/db'\nimport type { ${JSON.stringify(exported)} as Original } from ${JSON.stringify(specifier)}\n\ndeclare const source: DatabaseSource<typeof Original.schema>\nexport default source\nexport declare const engine: ${JSON.stringify(engine)}\n`;
  return { wrapper, bundle: header + await build.outputs[0]!.text(), declaration: types };
}
