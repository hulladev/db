import { basename, dirname, extname, relative, resolve, sep } from "node:path";
import { generateFunctions, type GenerationOptions } from "./codegen.ts";
import { compileWorker } from "./worker-codegen.ts";
import { FunctionAnalysis } from "./function-analysis.ts";
import { mkdir } from "node:fs/promises";
import { checkGeneratedDirectory } from "./schema-codegen.ts";
import { databaseEntry } from "./database-entry.ts";
import { catalogueImports, databaseFunctions } from "./database-function-discovery.ts";
import { generateSource } from "./source-codegen.ts";
import { captureDatabaseEntry } from "./database-capture.ts";
import { generateHost } from "./host-codegen.ts";
export { exportedDatabase } from "./database-entry.ts";

/** Generate caller modules next to an explicit database entrypoint, without connecting. */
export async function generateDatabase(entrypoint: string, options: Pick<GenerationOptions, "functions" | "moduleRoot" | "limits"> = {}): Promise<void> {
  const source = resolve(entrypoint);
  const analysis = new FunctionAnalysis();
  try {
    await analysis.open([source]);
    const declarations = await analysis.databaseDeclarations(source);
    const allowed = catalogueImports(analysis, declarations);
    const exports = await captureDatabaseEntry(source, analysis, declarations) ?? {};
    const entry = databaseEntry(exports);
    if (!entry) throw new TypeError("Database entrypoint must export exactly one database instance; found 0");
    const { database, name: databaseExport } = entry;
    const namespace = basename(source, extname(source));
    const outDir = resolve(dirname(source), "_generated", namespace);
    const selected = await databaseFunctions(database, source, outDir, declarations, options, analysis);
    const importPath = (path: string) => { const value = relative(outDir, path).split(sep).join("/"); return value.startsWith(".") ? value : `./${value}`; };
    const entries = Object.entries(selected);
    await checkGeneratedDirectory(outDir);
    await mkdir(outDir, { recursive: true });
    const shared = await generateSource(source, databaseExport, outDir, analysis, database.engine.name);
    const schemaExport = declarations.find(value => value.exportName === databaseExport)?.schemaExport;
    if (!schemaExport) throw new TypeError('Generation requires an exported schema from a separate inert authoring module');
    const schemaImport = `import { ${JSON.stringify(schemaExport.name)} as schema } from ${JSON.stringify(importPath(schemaExport.file))}`;
    const worker = `// Generated by @hulla/db. Do not edit.\n\n${schemaImport}\nimport { installWorker } from '@hulla/db/internal/worker'\n${entries.map(([, path], index) => `import * as module${index} from ${JSON.stringify(importPath(path))}`).join("\n")}\n\ninstallWorker({ schema, modules: {\n${entries.map(([name], index) => `  ${JSON.stringify(name)}: module${index},`).join("\n")}\n} })\n`;
    const bundle = await compileWorker(resolve(outDir, "_worker.ts"), worker, allowed);
    const host = await generateHost(source, databaseExport, declarations);
    await generateFunctions({ ...(options.limits === undefined ? {} : { limits: options.limits }), database, databaseExport, schema: source, outDir, modules: selected, databaseArtifacts: { worker, bundle, host }, databaseSource: shared }, analysis);
  } finally { await analysis.close(); }
}
