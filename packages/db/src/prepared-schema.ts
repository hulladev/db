import { basename, dirname, extname, resolve } from 'node:path';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { isDefinedSchema, type SchemaDefinition } from './schema.ts';

/** Prepared hosting reads generated metadata, never the application's eager bootstrap. */
export async function preparedSchema(entrypoint: string, expectedEngine?: string): Promise<{ schema: SchemaDefinition; directory: string } | undefined> {
  const directory = resolve(dirname(entrypoint), '_generated', basename(entrypoint, extname(entrypoint)));
  const path = resolve(directory, '_source.js');
  let contents: string;
  try { contents = await readFile(path, 'utf8'); }
  catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined; throw error; }
  if (!contents.startsWith('// Generated by @hulla/db. Do not edit.\n')) throw new TypeError('Expected generated database source metadata');
  const metadata = await import(pathToFileURL(path).href);
  if (!isDefinedSchema(metadata.default?.schema) || typeof metadata.engine !== 'string') throw new TypeError('Invalid generated database source metadata; regenerate the database entrypoint');
  if (expectedEngine && metadata.engine !== expectedEngine) throw new TypeError(`This host requires a ${expectedEngine} database; received ${metadata.engine}`);
  return { schema: metadata.default.schema, directory };
}
