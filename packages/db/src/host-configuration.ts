import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { defineConfig, type DatabaseConfig, type DatabaseSettings } from './config.ts';
import { exportedDatabase, exportedSchema } from './database-entry.ts';
import { preparedSchema } from './prepared-schema.ts';

async function preparedHost(path: string) {
  const prepared = await preparedSchema(path, 'postgres');
  if (!prepared) return undefined;
  const host = resolve(prepared.directory, '_host.js');
  const contents = await readFile(host, 'utf8').catch((error: NodeJS.ErrnoException) => {
    if (error.code === 'ENOENT') throw new Error('Missing database host settings; run hulla-db generate before hosting this entrypoint');
    throw error;
  });
  if (!contents.startsWith('// Generated by @hulla/db. Do not edit.\n')) throw new TypeError('Expected generated database host settings');
  const database = exportedDatabase(await import(pathToFileURL(host).href));
  if (database.engine.name !== 'postgres') throw new TypeError(`This host requires a postgres database; received ${database.engine.name}`);
  return { ...prepared, connection: database.connection as DatabaseSettings };
}

/** Prepared settings evaluate runtime URLs without opening the application's instance. */
export async function loadHostConfiguration(configPath: string) {
  const path = resolve(configPath);
  const direct = await preparedHost(path);
  if (direct) return {
    config: defineConfig({ database: { server: direct.connection } }) as DatabaseConfig,
    schemaPath: path, schema: direct.schema, directory: direct.directory, prepared: true,
  };
  const config = defineConfig((await import(pathToFileURL(path).href)).default as DatabaseConfig);
  const schemaPath = resolve(dirname(path), config.schema ?? 'db/schema.ts');
  const prepared = await preparedHost(schemaPath);
  const settings = prepared ? defineConfig({ ...config, database: { ...config.database, server: { ...prepared.connection, ...config.database.server } } }) : config;
  return {
    config: settings, schemaPath,
    schema: prepared?.schema ?? exportedSchema(await import(pathToFileURL(schemaPath).href), 'postgres'),
    directory: prepared?.directory ?? resolve(dirname(schemaPath), '_generated'),
    prepared: !!prepared,
  };
}
